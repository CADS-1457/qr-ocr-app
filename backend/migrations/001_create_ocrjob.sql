BEGIN;

CREATE TABLE IF NOT EXISTS ocrjob (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    owner_id INTEGER NOT NULL,

    status VARCHAR(30) NOT NULL DEFAULT 'pending',

    document_type VARCHAR(50),

    original_filename VARCHAR(255),

    mime_type VARCHAR(100),

    storage_path VARCHAR(1000),

    raw_text TEXT,

    structured_data TEXT,

    confidence DOUBLE PRECISION,

    error_message TEXT,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    started_at TIMESTAMP WITH TIME ZONE,

    completed_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_ocrjob_owner
        FOREIGN KEY (owner_id)
        REFERENCES useraccount(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_ocrjob_status
        CHECK (
            status IN (
                'pending',
                'processing',
                'completed',
                'failed'
            )
        )
);

CREATE INDEX IF NOT EXISTS ix_ocrjob_owner_id
    ON ocrjob(owner_id);

CREATE INDEX IF NOT EXISTS ix_ocrjob_status
    ON ocrjob(status);

CREATE INDEX IF NOT EXISTS ix_ocrjob_document_type
    ON ocrjob(document_type);

CREATE INDEX IF NOT EXISTS ix_ocrjob_created_at
    ON ocrjob(created_at);

COMMIT;